<#
  gen-revit-years.ps1 — generate the per-Revit-year component groups for
  RST.msi and RST-Machine.msi from the staged trees (feature #11, decision
  #10; the per-machine scope: feature #17, spec #20 §7).

  Product.wxs installs a Revit year only when that Revit is detected
  (REVIT<year>FOUND). Every component of the year must carry
      Condition="REVIT<year>FOUND OR REMOVE~="ALL""  Transitive="yes"
  and <Files Include> harvesting cannot carry a Condition. So this script
  walks build/R<NN>/{addins,app} and writes one component per file (file
  KeyPath, auto GUID from the target path: the same shape <Files> produced)
  into a generated .wxs that defines ComponentGroups Revit2025, Revit2026
  and Revit2027. RST.Installer.wixproj runs it before CoreCompile and
  compiles the output from obj\, so it is never edited or committed.

  -Scope user (RST.msi, the default; output unchanged from before -Scope):
    addins tree  -> Directory Addins<year>Dir   (%AppData%\Autodesk\Revit\Addins\<year>\)
    app tree     -> Directory R<NN>AppDir       (%AppData%\RST\R<NN>\app\)
  -Scope machine (RST-Machine.msi; the directories are Product.wxs's):
    *.addin      -> Directory Addins<year>Dir   (%ProgramData%\Autodesk\Revit\Addins\2025|2026\,
                                                 C:\Program Files\Autodesk\Revit\Addins\2027\)
                    with File Id RstAddin<year> and a util:XmlFile that sets
                    the manifest's <Assembly> to "[R<NN>Dir]RST.Bootstrap.dll"
                    at install time: the absolute path of that year's
                    bootstrap, because a per-machine manifest does not sit
                    beside it
    the rest of the addins tree (RST.Bootstrap.dll, .pdb)
                 -> Directory R<NN>Dir          (C:\Program Files\RST\R<NN>\)
    app tree     -> Directory R<NN>AppDir       (C:\Program Files\RST\R<NN>\app\)
  nested paths -> Component/@Subdirectory
  Every component path differs between the scopes, so every auto GUID does
  too (WU1 review N6).

  A missing or empty staged tree is an error: stage all three majors first
  (build/stage.sh R25|R26|R27). ci-smoke.ps1 and ci-machine-smoke.ps1 check
  the built Component table (condition, Transitive, per-year counts against
  the staged files).

  Runs under Windows PowerShell 5.1 and PowerShell 7.
#>
param(
  [Parameter(Mandatory)][string]$BuildRoot,
  [Parameter(Mandatory)][string]$Out,
  [ValidateSet('user', 'machine')][string]$Scope = 'user'
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$BuildRoot = (Resolve-Path $BuildRoot).Path
$years = [ordered]@{ '2025' = 'R25'; '2026' = 'R26'; '2027' = 'R27' }
$machine = $Scope -eq 'machine'

function Esc([string]$s) { [Security.SecurityElement]::Escape($s) }

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('<?xml version="1.0" encoding="utf-8"?>')
if ($machine) {
  [void]$sb.AppendLine('<!-- GENERATED by installer/gen-revit-years.ps1 -Scope machine from build/R<NN>/. Do not edit. -->')
  [void]$sb.AppendLine('<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs" xmlns:util="http://wixtoolset.org/schemas/v4/wxs/util">')
} else {
  [void]$sb.AppendLine('<!-- GENERATED by installer/gen-revit-years.ps1 from build/R<NN>/. Do not edit. -->')
  [void]$sb.AppendLine('<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">')
}
[void]$sb.AppendLine('  <Fragment>')

foreach ($year in $years.Keys) {
  $nn = $years[$year]
  $cond = Esc "REVIT${year}FOUND OR REMOVE~=`"ALL`""
  [void]$sb.AppendLine("    <ComponentGroup Id=`"Revit$year`">")
  $total = 0
  $manifests = 0
  foreach ($tree in @(@{ Name = 'addins'; Dir = "Addins${year}Dir" }, @{ Name = 'app'; Dir = "${nn}AppDir" })) {
    $root = Join-Path $BuildRoot (Join-Path $nn $tree.Name)
    if (-not (Test-Path $root -PathType Container)) { throw "staged tree missing: $root (run build/stage.sh $nn)" }
    $files = @(Get-ChildItem -Path $root -File -Recurse | Sort-Object FullName)
    if ($files.Count -eq 0) { throw "staged tree empty: $root" }
    foreach ($f in $files) {
      $rel = $f.FullName.Substring($root.Length).TrimStart('\', '/')
      $sub = Split-Path $rel -Parent
      $subAttr = if ($sub) { " Subdirectory=`"$(Esc ($sub -replace '/', '\'))`"" } else { '' }
      $dir = $tree.Dir
      $isManifest = $machine -and $tree.Name -eq 'addins' -and $f.Extension -eq '.addin'
      if ($machine -and $tree.Name -eq 'addins' -and -not $isManifest) { $dir = "${nn}Dir" }
      [void]$sb.AppendLine("      <Component Directory=`"$dir`"$subAttr Condition=`"$cond`" Transitive=`"yes`">")
      if ($isManifest) {
        if ($sub) { throw "a staged manifest must sit at the top of the addins tree: $rel" }
        $manifests++
        if ($manifests -gt 1) { throw "more than one staged manifest in $root" }
        [void]$sb.AppendLine("        <File Id=`"RstAddin$year`" Source=`"$(Esc $f.FullName)`" />")
        [void]$sb.AppendLine("        <util:XmlFile Id=`"RstAddin${year}Assembly`" File=`"[#RstAddin$year]`" ElementPath=`"/RevitAddIns/AddIn/Assembly`" Action=`"setValue`" Value=`"[${nn}Dir]RST.Bootstrap.dll`" SelectionLanguage=`"XPath`" Permanent=`"yes`" Sequence=`"1`" />")
      } else {
        [void]$sb.AppendLine("        <File Source=`"$(Esc $f.FullName)`" />")
      }
      [void]$sb.AppendLine('      </Component>')
    }
    $total += $files.Count
  }
  if ($machine -and $manifests -ne 1) { throw "no staged manifest (*.addin) in build/$nn/addins" }
  [void]$sb.AppendLine('    </ComponentGroup>')
  Write-Host "gen-revit-years: Revit$year <- $nn ($total files, scope $Scope)"
}

[void]$sb.AppendLine('  </Fragment>')
[void]$sb.AppendLine('</Wix>')

$outDir = Split-Path $Out -Parent
if ($outDir -and -not (Test-Path $outDir)) { New-Item -ItemType Directory -Force $outDir | Out-Null }
[IO.File]::WriteAllText($Out, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Host "gen-revit-years: wrote $Out"
