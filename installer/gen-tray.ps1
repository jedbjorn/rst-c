<#
  gen-tray.ps1 — generate the RST tray's file components for RST.msi from the
  staged tree build/Tray/ (feature #17, spec #20 §1; F17 WU1).

  build/stage.sh tray publishes RST.Tray.exe and its files once (not per Revit
  year). This script writes one component per staged file (file KeyPath, auto
  GUID from the target path, no condition: the tray installs whatever Revit
  years are detected) into ComponentGroup TrayFiles, Directory TrayDir
  (%LocalAppData%\Programs\RST\Tray\, Tray.wxs). RST.Installer.wixproj runs it
  before CoreCompile and compiles the output from obj\, so it is never edited
  or committed. Same shape as gen-revit-years.ps1.

  A missing or empty staged tree, or one without RST.Tray.exe, is an error:
  run build/stage.sh tray first.

  Runs under Windows PowerShell 5.1 and PowerShell 7.
#>
param(
  [Parameter(Mandatory)][string]$BuildRoot,
  [Parameter(Mandatory)][string]$Out
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$root = Join-Path (Resolve-Path $BuildRoot).Path 'Tray'
if (-not (Test-Path $root -PathType Container)) { throw "staged tray missing: $root (run build/stage.sh tray)" }
if (-not (Test-Path (Join-Path $root 'RST.Tray.exe') -PathType Leaf)) { throw "staged tray has no RST.Tray.exe: $root" }
$files = @(Get-ChildItem -Path $root -File -Recurse | Sort-Object FullName)

function Esc([string]$s) { [Security.SecurityElement]::Escape($s) }

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('<?xml version="1.0" encoding="utf-8"?>')
[void]$sb.AppendLine('<!-- GENERATED by installer/gen-tray.ps1 from build/Tray/. Do not edit. -->')
[void]$sb.AppendLine('<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">')
[void]$sb.AppendLine('  <Fragment>')
[void]$sb.AppendLine('    <ComponentGroup Id="TrayFiles">')
foreach ($f in $files) {
  $rel = $f.FullName.Substring($root.Length).TrimStart('\', '/')
  $sub = Split-Path $rel -Parent
  $subAttr = if ($sub) { " Subdirectory=`"$(Esc ($sub -replace '/', '\'))`"" } else { '' }
  [void]$sb.AppendLine("      <Component Directory=`"TrayDir`"$subAttr>")
  [void]$sb.AppendLine("        <File Source=`"$(Esc $f.FullName)`" />")
  [void]$sb.AppendLine('      </Component>')
}
[void]$sb.AppendLine('    </ComponentGroup>')
[void]$sb.AppendLine('  </Fragment>')
[void]$sb.AppendLine('</Wix>')

$outDir = Split-Path $Out -Parent
if ($outDir -and -not (Test-Path $outDir)) { New-Item -ItemType Directory -Force $outDir | Out-Null }
[IO.File]::WriteAllText($Out, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Host "gen-tray: TrayFiles <- build/Tray ($($files.Count) files); wrote $Out"
