#!/usr/bin/env python3
"""diff.py <old year> <new year>: census/diff-<new>-vs-<old>.md from the committed full tables (spec #34, AC10).

Per context present in either year: ids added, ids removed, and ids whose result changed (an id's result is the set
of its places' results, so "not-drawn at one place" shows). Python 3 stdlib only.
"""
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent.parent


def load(year):
    p = REPO / "census" / year / "full.tsv"
    lines = p.read_text(encoding="utf-8").splitlines()
    head = lines[0].split("\t")
    by = {}
    labels = {}
    tabs = {}
    for l in lines[1:]:
        r = dict(zip(head, l.split("\t")))
        by.setdefault(r["context"], {}).setdefault(r["id"], set()).add(r["result"])
        labels.setdefault(r["id"], r["label"])
        tabs.setdefault(r["id"], set()).add(r["tab"])
    return by, labels, tabs, (lines[1].split("\t")[1] if len(lines) > 1 else "")


def res(s):
    return "/".join(sorted(s))


def main(old, new):
    a, la, ta, ba = load(old)
    b, lb, tb, bb = load(new)
    out = [f"# Ribbon Tool Census: {new} vs {old}", "",
           f"Generated by `tools/census/diff.py {old} {new}` from `census/{old}/full.tsv` (build {ba}) and `census/{new}/full.tsv` (build {bb}).",
           "An id's result is the set of its places' results in that context. Labels are the newer year's.", ""]
    ctxs = sorted(set(a) | set(b), key=lambda c: (not c.startswith("project/"), c))
    out += ["## Summary", "", "| Context | ids " + old + " | ids " + new + " | added | removed | changed |", "|---|---|---|---|---|---|"]
    detail = []
    for c in ctxs:
        ia, ib = a.get(c, {}), b.get(c, {})
        added = sorted(set(ib) - set(ia))
        removed = sorted(set(ia) - set(ib))
        changed = sorted(i for i in set(ia) & set(ib) if ia[i] != ib[i])
        out.append(f"| `{c}` | {len(ia) if c in a else '—'} | {len(ib) if c in b else '—'} | {len(added)} | {len(removed)} | {len(changed)} |")
        if not (added or removed or changed):
            continue
        detail += [f"### `{c}`", ""]
        if c not in a:
            detail += [f"Context only in {new}.", ""]
        if c not in b:
            detail += [f"Context only in {old}.", ""]
        if added:
            detail += [f"**Added in {new}** ({len(added)})", "", "| id | label | tab | result |", "|---|---|---|---|"]
            detail += [f"| `{i}` | {lb.get(i, '')} | {', '.join(sorted(tb.get(i, [])))} | {res(ib[i])} |" for i in added] + [""]
        if removed:
            detail += [f"**Removed in {new}** ({len(removed)})", "", "| id | label | tab | result in " + old + " |", "|---|---|---|---|"]
            detail += [f"| `{i}` | {la.get(i, '')} | {', '.join(sorted(ta.get(i, [])))} | {res(ia[i])} |" for i in removed] + [""]
        if changed:
            detail += [f"**Changed result** ({len(changed)})", "", f"| id | label | {old} | {new} |", "|---|---|---|---|"]
            detail += [f"| `{i}` | {lb.get(i, la.get(i, ''))} | {res(ia[i])} | {res(ib[i])} |" for i in changed] + [""]
    out += ["", "## Per context", ""] + detail
    p = REPO / "census" / f"diff-{new}-vs-{old}.md"
    p.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {p}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
